
public class Operator_04 {

	public static void main(String[] args) {
		// 변수의 값을 증가/감소시킬 수 있는 연산자
		// ++ (증가 연산자) / -- (감소 연산자)
		// 특정 변수의 값을 1 증가하거나, 감소할 수 있는 연산자
		
		int num;
		
		num = 10;
		System.out.printf("num = %d\n", num);
		
		// num 변수의 값을 1 증가시키는 코드
		num = num + 1;
		System.out.printf("num = %d\n", num);
		
		// 증가 연산자를 사용한 1 증가
		num++;
		System.out.printf("num = %d\n", num);
		
		// 감소 연산자를 사용한 1 감소
		num--;
		System.out.printf("num = %d\n", num);

	}

}









