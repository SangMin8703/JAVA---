
public class Array_10 {

	public static void main(String[] args) {
		// 배열 변수와 일반 변수의 선언
		// 배열 기호의 위치
		// 일반적인 배열 변수는 다음과 같이 선언합니다.
		// 자료형 [] 배열변수명;
		// 예외적으로 다음과 같은 배열 변수의 선언이 가능합니다.
		// 자료형 배열변수명[];
		
		// int 형의 배열 변수 arr01, arr02, arr03을 선언하는 방법
		// 자료형 [] 의 형태를 사용하면 뒤에 나오는 변수들은 모두 배열 변수가 됩니다.
		int [] arr01, arr02, arr03;
		arr01 = new int[5];
		arr02 = new int[5];
		arr03 = new int[5];
		
		// 일반 int 형변수와 배열 변수를 동시에 선언하는 방법
		// arr04, arr06 은 일반적인 int 형 변수
		// arr05 는 배열변수로 선언됩니다.
		int arr04, arr05[], arr06;
		
		// arr04 = new int[5];
		arr04 = 10;
		arr06 = 11;
		
		arr05 = new int[5];

	}

}











