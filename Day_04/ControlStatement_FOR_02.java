
public class ControlStatement_FOR_02 {

	public static void main(String[] args) {
		// for 반복문은 if문과 마찬가지로 블럭을 지정하지 않으면 
		// 하나의 실행문을 반복해서 처리합니다.
		// 블럭을 지정하면 2개 이상의 실행문을 반복해서 처리할 수 있습니다.
		
		for( int i = 1 ; i <= 10 ; i++ ) {
			System.out.println("for 반복문의 실행문1");
			System.out.println("for 반복문의 실행문2");
		}

	}

}
